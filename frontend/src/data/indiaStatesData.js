// Quick helper to fetch a ward by ID
export function getWardById(id) {
  if (typeof id === 'number') {
    const idMap = {
      1: 'kar-blr-01',
      2: 'kar-blr-04',
      3: 'kar-blr-04',
      4: 'kar-blr-04',
      5: 'kar-blr-06',
      6: 'kar-blr-06',
      7: 'kar-blr-01',
      8: 'kar-blr-04',
    };
    const targetId = idMap[id] || 'kar-blr-04';
    return ALL_INDIA_WARDS.find((w) => w.id === targetId) || ALL_INDIA_WARDS[0];
  }
  return ALL_INDIA_WARDS.find((w) => w.id === id) || ALL_INDIA_WARDS[0];
}

// Generate 5-day daily forecast for a given ward
export function generateWard5DayForecast(ward) {
  if (!ward) return [];
  const baseTemp = Number(ward.temperature ?? ward.temp_c ?? 34.2);
  const baseWbgt = Number(ward.wbgt ?? ward.wbgt_c ?? 31.4);
  const baseHum = Number(ward.humidity ?? ward.humidity_pct ?? 65);
  const baseWind = Number(ward.windSpeed ?? ward.wind_speed_kmh ?? ward.wind_speed ?? 12.0);
  const days = ['Today', 'Tomorrow', 'Day 3', 'Day 4', 'Day 5'];
  const daysHi = ['आज', 'कल', 'तीसरा दिन', 'चौथा दिन', 'पांचवां दिन'];

  return days.map((day, i) => {
    const tempVariation = (i % 2 === 0 ? 0.8 : -0.6) * i;
    const maxTemp = Math.round((baseTemp + tempVariation + (i === 0 ? 0 : 2.2)) * 10) / 10;
    const minTemp = Math.round((baseTemp - 7.0 + tempVariation * 0.5) * 10) / 10;
    const wbgtMax = Math.round((baseWbgt + tempVariation * 0.7) * 10) / 10;
    const humidityAvg = Math.min(95, Math.max(30, Math.round(baseHum + (i % 3 === 0 ? 5 : -4))));
    const windSpeedAvg = Math.round((baseWind + (i % 2 === 0 ? 2 : -1.5)) * 10) / 10;

    let riskBand = 'Caution';
    if (wbgtMax >= 33.0) riskBand = 'Extreme';
    else if (wbgtMax >= 31.0) riskBand = 'Warning';

    const conditions = [
      'Sunny & Severe Heat',
      'Partly Cloudy & Humid',
      'Hot Winds / Loo',
      'Scattered Showers',
      'High Solar Radiance',
    ];
    const conditionsHi = [
      'धूप एवं गंभीर गर्मी',
      'आंशिक बादल एवं आर्द्रता',
      'गर्म हवाएं / लू',
      'छिटपुट वर्षा',
      'उच्च सौर विकिरण',
    ];

    const date = new Date();
    date.setDate(date.getDate() + i);
    const dateStr = `${date.getDate()} ${date.toLocaleString('en', { month: 'short' })}`;
    const trend = i === 0 ? 'steady' : tempVariation >= 0 ? 'up' : 'down';

    return {
      day,
      dayHi: daysHi[i],
      date: dateStr,
      temp: maxTemp,
      maxTemp,
      minTemp,
      wbgt: wbgtMax,
      wbgtMax,
      humidityAvg,
      windSpeedAvg,
      riskBand,
      trend,
      condition: conditions[i % conditions.length],
      conditionHi: conditionsHi[i % conditionsHi.length],
      rainProb: (ward.precipitation || 0) > 0 ? 60 + i * 5 : 10 + i * 5,
    };
  });
}

// Search all localities with robust matching for "Locality, City" queries
export function searchLocalities(query, stateId = null) {
  if (!query || typeof query !== 'string') return [];
  const cleanQ = query.trim().toLowerCase();
  if (cleanQ.length === 0) return [];

  let candidates = ALL_INDIA_WARDS;
  if (stateId && stateId !== 'all_india') {
    candidates = candidates.filter((w) => w.stateId === stateId);
  }

  // Split query by commas or spaces for flexible multi-token matching (e.g. "hsr, bengaluru" or "hsr blr")
  const tokens = cleanQ.split(/[\s,]+/).filter((t) => t.length > 0);

  return candidates.filter((w) => {
    const name = (w.name || '').toLowerCase();
    const nameHi = (w.nameHi || '').toLowerCase();
    const city = (w.city || '').toLowerCase();
    const stateName = (w.stateName || '').toLowerCase();
    const zone = (w.zone || '').toLowerCase();
    const wardNumber = (w.wardNumber || '').toLowerCase();
    const combined = `${name} ${city} ${stateName} ${zone} ${wardNumber} ${nameHi}`;

    return tokens.every((tok) => combined.includes(tok));
  });
}

// Get all localities within a given state ID
export function getLocalitiesByState(stateId) {
  if (!stateId || stateId === 'all_india') return ALL_INDIA_WARDS;
  return ALL_INDIA_WARDS.filter((w) => w.stateId === stateId);
}
